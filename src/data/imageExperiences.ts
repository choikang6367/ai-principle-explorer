const pixel = (
  id: string,
  x: number,
  y: number,
  r: number,
  g: number,
  b: number,
  label: string,
): ImagePixelSample => ({ id, x, y, r, g, b, label })

const feature = (
  id: string,
  kind: ImageFeatureKind,
  marker: ImageFeatureMarker,
  label: string,
  description: string,
  x: number,
  y: number,
  width: number,
  height: number,
): ImageFeature => ({ id, kind, marker, label, description, x, y, width, height })

const prediction = (label: string, probability: number): ImagePrediction => ({ label, probability })

const snapshot = (
  id: string,
  title: string,
  revealPercent: number,
  description: string,
  predictions: readonly ImagePrediction[],
): ImagePredictionSnapshot => ({ id, title, revealPercent, description, predictions })

